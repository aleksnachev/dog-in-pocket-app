// Разпознаване на спешни ситуации в свободен текст.
// Правилата са консервативни: при съмнение показваме спешната карта. Не поставят диагноза.
import { norm } from './text.js';

const ATE = '(изяд|изял|глътн|погълн|излапа|схруска|хапна|изпи|облиза|нагълта|ял[оа]? )';
const RULES = [
  { sos: 'chocolate', re: new RegExp(ATE + '.*(шоколад|какао|бонбон)|(шоколад|какао).*' + ATE) },
  { sos: 'grapes', re: new RegExp(ATE + '.*(грозд|стафид|коринт)|(грозд|стафид).*' + ATE) },
  { sos: 'xylitol', re: new RegExp(ATE + '.*(дъвк|ксилитол|без захар|паста за зъби)|(дъвк|ксилитол).*' + ATE) },
  { sos: 'rat_poison', re: /(отров.*(миш|плъх|гризач)|примамк|родентицид)/ },
  { sos: 'antifreeze', re: /(антифриз|етилен|течност за чистачки|спирачна течност)/ },
  { sos: 'meds', re: new RegExp(ATE + '.*(хапч|лекарств|таблетк|ибупрофен|парацетамол|аспирин|нурофен|аналгин)|(хапч|лекарств|таблетк).*' + ATE) },
  { sos: 'onion', re: new RegExp(ATE + '.*(лук|чесън|праз)') },
  { sos: 'poison', re: /(отрав|отров|натров|токсичн)|(изяд|глътн|погълн).*(гъб|препарат|белин|почиств|олеандър|тис |лале|нарцис|макадами|алкохол|ракия|бира|вино|тесто|кафе)/ },
  { sos: 'swallowed', re: /(глътн|погълн|изяд|нагълта).*(чорап|играчк|топк|камък|камъч|кочан|кост|конец|корда|игла|ластик|бельо|пластмас|предмет|кърп|чужд)/ },
  { sos: 'breathing', re: /(не може да диша|не диша нормално|трудно диша|задъхва се|задушава|посиня|сини венци|хрипти силно)/ },
  { sos: 'choking', re: /(задав|заседна|в гърлото|дави се|не може да преглътне)/ },
  { sos: 'gdv', re: /(подут|издут|надут|раздут|твърд).{0,12}(корем|стомах)|(корем|стомах).{0,15}(подут|издут|надут|раздут)|(напъва|опитва|иска).{0,10}(да повърне|повръща).{0,25}(не може|нищо|без да)|усукан|усукване|не може да повърне/ },
  { sos: 'seizure', re: /(гърч|конвулс|епилептич|припадък|тресе се цял|трепери цял.*не реагира)/ },
  { sos: 'collapse', re: /(припадна|колапс|в безсъзнание|не реагира|загуби съзнание|не диша|няма пулс|падна и не става)/ },
  { sos: 'heatstroke', re: /(топлинен удар|прегря|слънчев удар|в колата.*(жега|горещ|слънце)|(жега|горещ).*(задъхва|колапс|повръща|не става))/ },
  { sos: 'bleeding', re: /(кърви (силно|много|не спира)|кръвта не спира|шурти кръв|силно кървене|дълбока рана)/ },
  { sos: 'trauma', re: /(блъсна|удари го кола|прегази|падна от (високо|балкон|тераса)|счупен|счупи крак|не може да стъпи)/ },
  { sos: 'snake', re: /(змия|усойниц|пепелянк)/ },
  { sos: 'electric', re: /(токов удар|удари го ток|прегриза кабел|гризе кабел|мълния)/ },
  { sos: 'burn', re: /(изгор|попар|вряла вода|киселина)/ },
  { sos: 'urine', re: /(не може да (пишка|уринира)|не пишка|напъва да пишка|не е пишкал)/ },
  { sos: 'parvo', re: /(кученц.*(кървава диария|кръв.*диария|повръща.*диария|диария.*повръща))/ },
  { sos: 'pyometra', re: /(гной|течение).*(вулв|половите|отзад)|пиометр/ },
  { sos: 'water_intox', re: /(плува|плуване|във водата|море|езеро).*(залита|повръща|отпадна|колапс)/ },
  { sos: 'eye', re: /(око|очи).*(удар|нарани|забито|кърви|подуто|затвор)/ },
  { sos: 'sting', re: /(ужили|пчела|оса|стършел).*(подут|муцун|лице|гърл|диша|много)|подуване.*(муцун|гърл|шия)/ },
];

// Червени флагове, които правят дори „обикновен“ симптом спешен
const RED = /(кръв|кърв|не реагира|колапс|бледи венци|сини венци|не диша|гърч|постоянно|непрекъснато|не спира|цял ден|от вчера|кученце.*(повръща|диария))/;

export function triage(q) {
  const t = ' ' + norm(q) + ' ';
  const hits = [];
  for (const r of RULES) if (r.re.test(t)) hits.push(r.sos);
  return { sos: [...new Set(hits)], red: RED.test(t) };
}
